import { session, evidence, fm, sleep } from "./lib.mjs";
const s = await session();
await s.reloadPlugin();
await s.setSettings({ language: "en" });
const p = "Uji 0.8/RT Jatuh tempo.md";
await s.patchSettings("s.retrieval.adjustInterval=false");
const before = await s.read(p);
await s.openFile(p); await sleep(300);
await s.cmd("recall"); await sleep(700);
await s.fill(["something from memory about this"]);
await s.clickModal("Submit answer"); await sleep(300);
await s.clickModal("Next question"); await sleep(300);
await s.fill(["another answer from memory here"]);
await s.clickModal("Submit answer"); await sleep(300);
await s.clickModal("Forgot"); await sleep(200);
await s.shot("T-RT5b", "adjust review dimatikan, Lupa dipilih");
await s.clickModal("Finish"); await sleep(1200);
const after = await s.read(p);
const n = await s.notices();
await s.sourceView(p); await sleep(500);
await s.shot("T-RT5b", "callout retrieval tertulis, review tidak berubah");
const ok = /\[!retrieval\]/.test(after) && /Bank · forgot/.test(after) && fm(before) === fm(after);
evidence("T-RT5b", `# T-RT5b: ${ok ? "PASS" : "FAIL"}\n\nadjustInterval=false, Forgot chosen. frontmatter unchanged=${fm(before) === fm(after)}; notices=${JSON.stringify(n)}\n\n## frontmatter before\n\`\`\`\n${fm(before)}\n\`\`\`\n## after\n\`\`\`\n${fm(after)}\n\`\`\`\n`);
console.log("T-RT5b", ok ? "PASS" : "FAIL");
await s.patchSettings("s.retrieval.adjustInterval=true");
s.c.close();
